#!/usr/bin/env python3
"""Build Vulkan DDGI connection shaders from the canonical geometry query.

All outputs are published after requested compiles and validation pass.
--verify-existing additionally requires the eight established variants to remain
byte-identical; normal builds may regenerate them after intentional source edits.
"""
from pathlib import Path
import argparse
import hashlib
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
S = ROOT / 'Engine/Graphics/Vulkan/shaders'
LUMEN = S / 'Lumen'

def adapter():
    text = (LUMEN / 'GeometryFirstHit.glsl').read_text()
    for a, b in [(13,23),(14,24),(15,25),(16,26)]:
        old = f'binding={a},'
        if text.count(old) != 1:
            raise RuntimeError(f'expected one {old} in canonical query')
        text = text.replace(old, f'binding={b},')
    return '// Generated by scripts/build_ddgi_connections_spv.py; do not edit query logic here.\n#if 0\n#include "GeometryFirstHit.glsl"\n#endif\n' + text

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check-adapter', action='store_true')
    parser.add_argument('--adapter-only', action='store_true')
    parser.add_argument('--verify-existing', action='store_true', help='Require established variants to remain byte-identical')
    parser.add_argument('--variant', choices=['all','default','gate','replace','source','legacy','generic','anyhit','compact','packed','traversal-audit','query-kernel','bounds-first','cacheless64','cacheless32','equal-box','instance-payload','pair'], default='all')
    args = parser.parse_args()
    target = LUMEN / 'GeometryFirstHitGather.glsl'
    expected = adapter()
    if args.check_adapter:
        if not target.exists() or target.read_text() != expected:
            raise RuntimeError('canonical geometry binding adapter is stale')
        return
    # A stale adapter must be regenerated explicitly; compiling must not mutate
    # an unrelated source file as a side effect.
    if args.adapter_only:
        if not target.exists() or target.read_text() != expected:
            target.write_text(expected)
        return
    if not target.exists() or target.read_text() != expected:
        raise RuntimeError('canonical geometry binding adapter is stale; run --adapter-only')
    variants = {'default': ([], 'DDGIGIGather.comp.spv'),
                'gate': (['-DDDGI_GEOMETRY_CONNECTIONS'], 'DDGIGIGather_geometry.comp.spv'),
                'replace': (['-DDDGI_GEOMETRY_CONNECTIONS','-DDDGI_GEOMETRY_REPLACE'],
                            'DDGIGIGather_geometry_replace.comp.spv')}
    variants.update({'source': (['-DDDGI_GLOSSY_SOURCE_AUDIT'], 'DDGIGIGather_source.comp.spv'),
                     'legacy': (['-DDDGI_LEGACY_CONSUMERS'], 'DDGIGIGather_legacy.comp.spv'),
                     'generic': ([], 'DDGIGIGather.spv'),
                     'anyhit': (['-DDDGI_GEOMETRY_CONNECTIONS','-DDDGI_GEOMETRY_REPLACE','-DDDGI_GEOMETRY_ANY_HIT'], 'DDGIGIGather_geometry_anyhit.comp.spv'),
                     'compact': (['-DDDGI_GEOMETRY_CONNECTIONS','-DDDGI_GEOMETRY_REPLACE','-DDDGI_GEOMETRY_ANY_HIT','-DDDGI_GEOMETRY_COMPACT_STACKS'], 'DDGIGIGather_geometry_compact.comp.spv'),
                     'packed': (['-DDDGI_GEOMETRY_CONNECTIONS','-DDDGI_GEOMETRY_REPLACE','-DDDGI_GEOMETRY_ANY_HIT','-DDDGI_GEOMETRY_COMPACT_STACKS','-DDDGI_GEOMETRY_COMPACT_PACKED'], 'DDGIGIGather_geometry_compact_packed.comp.spv'),
                     'traversal-audit': (['-DDDGI_GEOMETRY_CONNECTIONS','-DDDGI_GEOMETRY_REPLACE','-DDDGI_GEOMETRY_ANY_HIT','-DDDGI_TRAVERSAL_AUDIT'], 'DDGIGIGather_geometry_traversal_audit.comp.spv'),
                     'query-kernel': (['-DDDGI_GEOMETRY_CONNECTIONS','-DDDGI_GEOMETRY_REPLACE','-DDDGI_GEOMETRY_ANY_HIT','-DDDGI_GEOMETRY_QUERY_KERNEL'], 'DDGIGIGather_geometry_query_kernel.comp.spv'),
                     'bounds-first': (['-DDDGI_GEOMETRY_CONNECTIONS','-DDDGI_GEOMETRY_REPLACE','-DDDGI_GEOMETRY_ANY_HIT','-DDDGI_GEOMETRY_QUERY_KERNEL','-DDDGI_GEOMETRY_BOUNDS_FIRST'], 'DDGIGIGather_geometry_bounds_first.comp.spv'),
                     'cacheless64': (['-DDDGI_GEOMETRY_CONNECTIONS','-DDDGI_GEOMETRY_REPLACE','-DDDGI_GEOMETRY_ANY_HIT','-DDDGI_GEOMETRY_QUERY_KERNEL','-DDDGI_GATHER_CACHELESS'], 'DDGIGIGather_geometry_cacheless64.comp.spv'),
                     'cacheless32': (['-DDDGI_GEOMETRY_CONNECTIONS','-DDDGI_GEOMETRY_REPLACE','-DDDGI_GEOMETRY_ANY_HIT','-DDDGI_GEOMETRY_QUERY_KERNEL','-DDDGI_GATHER_CACHELESS','-DDDGI_GATHER_CACHELESS_32'], 'DDGIGIGather_geometry_cacheless32.comp.spv')})
    variants['equal-box'] = (['-DDDGI_GEOMETRY_CONNECTIONS','-DDDGI_GEOMETRY_REPLACE','-DDDGI_GEOMETRY_ANY_HIT','-DDDGI_GEOMETRY_QUERY_KERNEL','-DDDGI_GEOMETRY_EQUAL_BOX'], 'DDGIGIGather_geometry_equal_box.comp.spv')
    variants['instance-payload'] = (['-DDDGI_GEOMETRY_CONNECTIONS','-DDDGI_GEOMETRY_REPLACE','-DDDGI_GEOMETRY_ANY_HIT','-DDDGI_GEOMETRY_QUERY_KERNEL','-DDDGI_INSTANCE_PAYLOAD_CACHE'], 'DDGIGIGather_geometry_instance_payload.comp.spv')
    variants['pair'] = (['-DDDGI_GEOMETRY_CONNECTIONS','-DDDGI_GEOMETRY_REPLACE','-DDDGI_GEOMETRY_ANY_HIT','-DDDGI_GEOMETRY_QUERY_KERNEL','-DDDGI_GEOMETRY_PAIR'], 'DDGIGIGather_geometry_pair.comp.spv')
    selected = list(variants) if args.variant == 'all' else [args.variant]
    if args.verify_existing:
        selected = list(dict.fromkeys([name for name in variants if name != 'pair'] + selected))
    results = []
    with tempfile.TemporaryDirectory(prefix='primal-ddgi-connections-') as tmp:
        for variant in selected:
            macros, name = variants[variant]
            out = Path(tmp) / name
            subprocess.run(['glslangValidator','--quiet','-V','-I'+str(S), *macros,
                '-Dddgi_gi_gather=main','--source-entrypoint','main','-e','ddgi_gi_gather',
                str(LUMEN/'DDGIGIGather.comp'),'-o',str(out)], check=True)
            subprocess.run(['spirv-val','--target-env','vulkan1.2',str(out)], check=True)
            data = out.read_bytes()
            identical = (LUMEN/name).exists() and data == (LUMEN/name).read_bytes()
            if args.verify_existing and variant != 'pair' and not identical:
                raise RuntimeError(f'{variant} no longer matches existing {name}; nothing written')
            results.append((variant, name, data, identical))
    for variant, name, data, identical in results:
        if not identical:
            (LUMEN/name).write_bytes(data)
        else:
            (LUMEN/name).touch() # The build freshness gate tracks source mtimes.
        print(f'{variant} {name} sha256={hashlib.sha256(data).hexdigest()}' +
              (' byte-identical to existing' if identical else ' rebuilt'))

if __name__ == '__main__':
    main()
