#!/usr/bin/env python3
"""Vulkan-only albedo gradient sampling; other channels and canonical WGSL stay literal."""
from pathlib import Path
import argparse,subprocess,tempfile,json,hashlib
R=Path(__file__).resolve().parents[1];base=R/'Engine/Graphics/Dawn/shaders/Nanite/GPUDrivenDraw.wgsl';D=R/'Engine/Graphics/Vulkan/shaders/Nanite';generated=D/'GPUDrivenDrawAlbedoMips.wgsl';output=D/'GPUDrivenDrawAlbedoMips.frag.spv'
def derive():
 s=base.read_text();old='    let scaled_uv = fract(in.uv * mat.uv_scale);'
 assert s.count(old)==1
 s=s.replace(old,'''    // Derivatives of the continuous coordinates, before wrap or texture-index branches.
    let raw_scaled_uv = in.uv * mat.uv_scale;
    let albedo_dx = dpdx(raw_scaled_uv);
    let albedo_dy = dpdy(raw_scaled_uv);
    let scaled_uv = fract(raw_scaled_uv);''')
 old='''textureSampleLevel(albedo_textures, texture_sampler,
                                           scaled_uv, mat.albedo_texture_idx, 0.0)'''
 assert s.count(old)==1
 return '// Generated by scripts/build_vulkan_albedo_mips_spv.py from canonical WGSL.\n'+s.replace(old,'''textureSampleGrad(albedo_textures, texture_sampler,
                                          scaled_uv, mat.albedo_texture_idx, albedo_dx, albedo_dy)''')
p=argparse.ArgumentParser();p.add_argument('--check-source',action='store_true');a=p.parse_args()
if a.check_source:
 assert generated.read_text()==derive(),'Vulkan albedo mip sampling source is stale'
else:
 with tempfile.TemporaryDirectory(prefix='primal-albedo-spv-') as tmp:
  path=Path(tmp);copy=path/'baseline.wgsl';copy.write_text(base.read_text());out=path/'baseline.spv'
  subprocess.run(['naga',str(copy),str(out)],check=True)
  assert out.read_bytes()==(D/'GPUDrivenDraw.spv').read_bytes(),'Canonical WGSL no longer reproduces active Vulkan baseline; requalify first'
 if not generated.exists() or generated.read_text()!=derive():generated.write_text(derive())
 subprocess.run(['naga',str(generated),str(output)],check=True)
 subprocess.run(['spirv-val','--target-env','vulkan1.2',str(output)],check=True)
 print(output)
