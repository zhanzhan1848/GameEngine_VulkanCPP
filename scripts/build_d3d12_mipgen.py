#!/usr/bin/env python3
"""build_d3d12_mipgen.py -- offline precompile + static-embed cycle for the
D3D12 MipGen shader pair (R14-2, scheme B: no build-time HLSL compiler).

Why offline (runbook section 23-2): the R13-A build-time dxc/fxc probe chain
failed on the user's Windows box with 0x80070459 (ERROR_NO_UNICODE_TRANSLATION)
+ MSB8066 regardless of code page. Precompiling on macOS with the local dxc
and checking in the embedded header removes the Windows build-time compiler
dependency entirely.

Chain (profile selection recorded in runbook section 23-2):
  Engine/Graphics/RHI/Platforms/D3D12/Shaders/MipGen.hlsl (pure ASCII)
    -> dxc -T vs_6_0 -E MipGenVS -Fo <tmp>/MipGen.vs.cso  (DXIL, SM6.0)
    -> dxc -T ps_6_0 -E MipGenPS -Fo <tmp>/MipGen.ps.cso  (DXIL, SM6.0)
    -> rewrite Engine/Graphics/RHI/Platforms/D3D12/D3D12MipGenShaders.h
       (checked-in static header consumed by D3D12Mipgen.cpp: byte arrays
       kMipGenVsBytes/kMipGenPsBytes + size constants in namespace
       primal::graphics::rhi::d3d12)

The header records source SHA256 and both cso SHA256 values (manifest style
aligned with scripts/build_d3d12_shaders.py: source SHA -> product SHA).

Modes:
  default        compile + rewrite the embedded header + print SHAs
  --check        recompile to a temp dir and verify: recorded source SHA
                 matches the current MipGen.hlsl, recompiled cso SHAs match
                 the recorded ones, and the array sizes match the size
                 constants. Any drift -> exit 1 (freshness gate).

dxc byte reproducibility was measured (same dxc + same source -> identical
cso SHA across runs), which is what makes the --check recompile comparison
meaningful. Note comment-only source edits keep the cso identical (the DXBC
container carries no source text), so source-SHA drift alone is reported as
STALE for regeneration hygiene even when cso bytes would not change.

Standard library only; tool path overridable via D3D12_DXC (default
/usr/local/bin/dxc).
"""
import argparse
import datetime
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(
    REPO, "Engine/Graphics/RHI/Platforms/D3D12/Shaders/MipGen.hlsl")
HEADER = os.path.join(
    REPO, "Engine/Graphics/RHI/Platforms/D3D12/D3D12MipGenShaders.h")

DXC = os.environ.get("D3D12_DXC", "/usr/local/bin/dxc")

STAGES = [
    # (stage label, profile, entry, array name, size-constant name)
    ("vs", "vs_6_0", "MipGenVS", "kMipGenVsBytes", "kMipGenVsSize"),
    ("ps", "ps_6_0", "MipGenPS", "kMipGenPsBytes", "kMipGenPsSize"),
]

BYTES_PER_LINE = 16


def run(cmd, timeout=120):
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
        return p.returncode, (p.stderr or "") + (p.stdout or "")
    except subprocess.TimeoutExpired:
        return 124, "TIMEOUT"
    except FileNotFoundError as e:
        return 127, f"missing tool: {e}"


def tool_version(cmd):
    rc, out = run(cmd, timeout=30)
    return out.strip().splitlines()[0] if rc == 0 and out.strip() else "unknown"


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def compile_stage(stage, profile, entry, cso_out):
    """Compile one stage. Returns (ok, cso_sha, message)."""
    rc, out = run([DXC, SRC, "-T", profile, "-E", entry, "-Fo", cso_out])
    if rc != 0:
        return False, None, f"dxc failed (rc={rc}): {out.strip()[:2000]}"
    if out.strip():
        return False, None, f"dxc emitted output (expected silent): {out.strip()[:2000]}"
    if not os.path.isfile(cso_out) or os.path.getsize(cso_out) == 0:
        return False, None, "dxc produced no output blob"
    return True, sha256_file(cso_out), ""


def format_array(data, name):
    lines = []
    for off in range(0, len(data), BYTES_PER_LINE):
        chunk = data[off:off + BYTES_PER_LINE]
        lines.append(", ".join(f"0x{b:02x}" for b in chunk) + ",")
    body = "\n".join(f"    {ln}" if ln else "    " for ln in lines)
    return f"constexpr unsigned char {name}[] = {{\n{body}\n}};"


HEADER_MARKER_RE = re.compile(
    r"^// source_sha256=(?P<src>[0-9a-f]{64}) "
    r"vs_cso_sha256=(?P<vs>[0-9a-f]{64}) "
    r"ps_cso_sha256=(?P<ps>[0-9a-f]{64})$", re.MULTILINE)


def build_header_text(src_sha, stage_info, dxc_ver, generated_utc):
    lines = [
        "// D3D12MipGenShaders.h - statically embedded MipGen shader blobs.",
        "//",
        "// Generated by scripts/build_d3d12_mipgen.py -- DO NOT EDIT BY HAND.",
        "// Regenerate after editing MipGen.hlsl:",
        "//   python3 scripts/build_d3d12_mipgen.py",
        "//",
        "// Offline-precompile scheme (R14-2): blobs were compiled on macOS",
        f"// with dxc ({dxc_ver}); no HLSL compiler runs at CMake build time",
        "// (removes the Windows 0x80070459 / MSB8066 failure class at the",
        "// root). Profiles: vs_6_0 / ps_6_0 (DXIL; dxc 1.9.0 promotes 5_0",
        "// profiles to 6.0 anyway - see runbook section 23-2).",
        "//",
        f"// generated_utc={generated_utc}",
        f"// source_sha256={src_sha} "
        f"vs_cso_sha256={stage_info['vs']['sha']} "
        f"ps_cso_sha256={stage_info['ps']['sha']}",
        "// source: Engine/Graphics/RHI/Platforms/D3D12/Shaders/MipGen.hlsl",
        "// consumer: D3D12MipGen.cpp (kMipGen*Bytes + kMipGen*Size).",
        "#pragma once",
        "#include <cstddef>",
        "namespace primal::graphics::rhi::d3d12 {",
    ]
    for stage, profile, entry, arr, size_const in STAGES:
        info = stage_info[stage]
        lines.append("")
        lines.append(f"// {stage.upper()} blob: -T {profile} -E {entry} "
                     f"({len(info['bytes'])} bytes, sha256 {info['sha']})")
        lines.append(format_array(info["bytes"], arr))
        lines.append(f"constexpr std::size_t {size_const} = {len(info['bytes'])};")
    lines.append("} // namespace primal::graphics::rhi::d3d12")
    return "\n".join(lines) + "\n"


def do_build():
    if not os.path.isfile(SRC):
        print(f"FATAL: source missing: {SRC}", file=sys.stderr)
        return 2
    if not (shutil.which(DXC) or os.path.isfile(DXC)):
        print(f"FATAL: dxc not found: {DXC}", file=sys.stderr)
        return 2

    stage_info = {}
    problems = []
    with tempfile.TemporaryDirectory() as td:
        for stage, profile, entry, _, _ in STAGES:
            cso = os.path.join(td, f"MipGen.{stage}.cso")
            ok, sha, msg = compile_stage(stage, profile, entry, cso)
            if not ok:
                problems.append(f"{stage}: {msg}")
                continue
            with open(cso, "rb") as f:
                data = f.read()
            stage_info[stage] = {"sha": sha, "bytes": data}
            print(f"[build] {stage}: dxc -T {profile} -E {entry} -> "
                  f"{len(data)}B sha256={sha[:16]}..")
    if problems:
        for p in problems:
            print(f"FAIL {p}", file=sys.stderr)
        return 1

    src_sha = sha256_file(SRC)
    dxc_ver = tool_version([DXC, "--version"])
    generated_utc = datetime.datetime.now(datetime.timezone.utc).isoformat(
        timespec="seconds")
    text = build_header_text(src_sha, stage_info, dxc_ver, generated_utc)
    with open(HEADER, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"header: {os.path.relpath(HEADER, REPO)}")
    print(f"source_sha256={src_sha}")
    for stage in stage_info:
        print(f"{stage}_cso_sha256={stage_info[stage]['sha']}")
    return 0


def do_check():
    if not os.path.isfile(HEADER):
        print(f"FRESHNESS FAIL: embedded header missing: {HEADER}\n"
              f"Run: python3 scripts/build_d3d12_mipgen.py", file=sys.stderr)
        return 1
    if not os.path.isfile(SRC):
        print(f"FRESHNESS FAIL: source missing: {SRC}", file=sys.stderr)
        return 1
    with open(HEADER, "r", encoding="utf-8") as f:
        head_text = f.read()
    m = HEADER_MARKER_RE.search(head_text)
    if not m:
        print("FRESHNESS FAIL: header lacks the SHA marker line "
              "(regenerate it with scripts/build_d3d12_mipgen.py)",
              file=sys.stderr)
        return 1

    stale = []
    src_sha = sha256_file(SRC)
    if src_sha != m.group("src"):
        stale.append(f"MipGen.hlsl changed since header was generated "
                     f"(header {m.group('src')[:12]}.., now {src_sha[:12]}..) "
                     f"- rerun scripts/build_d3d12_mipgen.py")

    if not (shutil.which(DXC) or os.path.isfile(DXC)):
        print(f"FRESHNESS FAIL: dxc not found for recompile check: {DXC}",
              file=sys.stderr)
        return 1
    with tempfile.TemporaryDirectory() as td:
        for stage, profile, entry, arr, size_const in STAGES:
            recorded = m.group(stage)
            cso = os.path.join(td, f"MipGen.{stage}.cso")
            ok, sha, msg = compile_stage(stage, profile, entry, cso)
            if not ok:
                stale.append(f"{stage}: recompile failed: {msg}")
                continue
            if sha != recorded:
                stale.append(f"{stage}: cso sha mismatch (header "
                             f"{recorded[:12]}.., recompiled {sha[:12]}..) "
                             f"- header bytes are stale or dxc changed")
            # Array-size constants must match the recorded header text.
            size_m = re.search(rf"constexpr std::size_t {size_const} = (\d+);",
                               head_text)
            if not size_m:
                stale.append(f"{stage}: size constant {size_const} not found "
                             "in header")
            elif int(size_m.group(1)) != os.path.getsize(cso):
                stale.append(f"{stage}: size constant {size_const}="
                             f"{size_m.group(1)} != recompiled "
                             f"{os.path.getsize(cso)}")

    if stale:
        print("D3D12 MipGen embedded-header freshness check FAILED:",
              file=sys.stderr)
        for s in stale:
            print(f"  STALE: {s}", file=sys.stderr)
        return 1
    print("D3D12 MipGen embedded-header freshness check passed "
          f"({len(STAGES)} blobs).")
    return 0


def main():
    ap = argparse.ArgumentParser(
        description="Offline precompile + static embed for D3D12 MipGen "
                    "shaders (R14-2).")
    ap.add_argument("--check", action="store_true",
                    help="freshness gate: recompile and compare SHAs against "
                         "the checked-in header; drift exits 1")
    args = ap.parse_args()
    return do_check() if args.check else do_build()


if __name__ == "__main__":
    sys.exit(main())
