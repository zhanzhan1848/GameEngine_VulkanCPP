#!/usr/bin/env python3
"""Generate the Dawn demo browser manifest from the versioned asset inventory."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = 'https://pub-e0a46516544c4038bea407d5fe82f92a.r2.dev/'
data = json.loads((ROOT / 'asset-manifests/sponza.json').read_text())
assets = []
gi_inputs = []
for a in data['assets']:
    path = a['path']
    if 'dawn-mode11' in a['groups'] and 'dawn-web' not in a['groups']:
        target = gi_inputs
    elif 'dawn-web' in a['groups']:
        target = assets
    else:
        continue
    if not path.startswith('EngineTest/assets/'):
        raise ValueError('unexpected asset path')
    entry = {'url': BASE + a['key'], 'fsPath': '/assets/' + path.removeprefix('EngineTest/assets/'), 'sha256': a['sha256'], 'size': a['size']}
    if 'gzip' in a:
        entry['gzip'] = {'url': BASE + a['gzip']['key'], 'size': a['gzip']['size']}
    target.append(entry)
if not any(a['fsPath'] == '/assets/Sponza.model' for a in assets) or len(assets) < 3:
    raise SystemExit('Dawn model or textures missing from inventory')
output = '// Generated by scripts/generate_dawn_web_manifest.py; do not edit.\nwindow.DAWN_ASSETS = ' + json.dumps(assets, indent=2) + ';\n'
output += 'window.DAWN_GI_INPUTS = ' + json.dumps(gi_inputs, indent=2) + ';\n'
(ROOT / 'wasm/dawn_assets_manifest.js').write_text(output)
print(f'Generated {len(assets)} Dawn assets')
